"""
Часы стенда: монотонные сроки и обнаружение простоя хоста.

Прогон идёт часами без человека, а Mac по умолчанию засыпает через минуту
простоя (`pmset -g`, `sleep 1`). Во сне монотонные часы стоят, а настенные идут,
и стенд от этого получает две беды сразу.

Первая: срок, отмеренный настенными часами, во сне исчерпывается мгновенно.
Стенд выходил из ожидания, ни разу не опросив плату, и объявлял «сеанс не
доиграл за 125 с» - при том что pytest намерил на этот тест 2,56 с. Вторая: пока
хост спал, лог никто не вычитывал, кольцо METF переполнялось, и любое
утверждение о логе после этого ничего не стоит.

Поэтому все сроки стенда отмеряются `time.monotonic()`, а расхождение двух часов
замечается и валит прогон целиком: за время сна наблюдения нет ни у кого, и
обстановка устройства неизвестна.

Цена известна: прогон 2026-09-27 16-12 шёл 4 ч 41 мин настенных, pytest намерил
1 ч 29 мин, и 9 падений из 10 пришлись ровно на двенадцать провалов по 900-1040 с.
"""
import os
import subprocess
import time

from loguru import logger

# Порог, после которого расхождение часов считается простоем хоста, а не
# неточностью замера. Обычный разброс двух чтений часов - микросекунды.
HOST_JUMP_S = 5.0


class HostAsleep(Exception):
    """
    Хост стоял: наблюдения за это время нет ни у кого.

    Не `AssertionError` намеренно - это не приговор устройству, и подниматься
    он должен мимо всех обработчиков, которые разбирают отказы прошивки.
    """


class HostClock:
    """Пара часов, по расхождению которых виден простой хоста."""

    def __init__(self) -> None:
        self._mono = time.monotonic()
        self._wall = time.time()
        self.slept = 0.0        # сколько всего хост простоял за прогон
        self.last = 0.0         # последний замеченный провал

    def tick(self) -> float:
        """
        Замерить расхождение с прошлого замера. Возвращает длину провала или 0.

        Зовётся из каждого круга ожидания: два чтения часов стоят наносекунды.
        """
        mono, wall = time.monotonic(), time.time()
        jump = (wall - self._wall) - (mono - self._mono)
        self._mono, self._wall = mono, wall
        if jump < HOST_JUMP_S:
            return 0.0
        self.slept += jump
        self.last = jump
        logger.error(f'компьютер стенда не работал {jump:.0f} с '
                     f'(настенные часы ушли вперёд монотонных): наблюдения за это '
                     f'время нет, об устройстве сказать нечего')
        return jump

    def check(self, what: str) -> None:
        """Тот же замер, но провал поднимает `HostAsleep`."""
        jump = self.tick()
        if jump:
            raise HostAsleep(
                f'компьютер стенда не работал {jump:.0f} с во время «{what}»: '
                f'лог устройства за это время никто не вычитывал, кольцо METF '
                f'могло переполниться, и наблюдение недостоверно')

    def note(self) -> str:
        """Приписка к отказу: простаивал ли хост за прогон."""
        if not self.slept:
            return ''
        return (f'. Хост за прогон простоял {self.slept:.0f} с '
                f'(последний провал {self.last:.0f} с)')


host = HostClock()


def keep_awake() -> subprocess.Popen[bytes] | None:
    """
    Не дать хосту уснуть на время прогона: `caffeinate -ims -w <наш pid>`.

    `-w` привязывает удержание к жизни процесса pytest, поэтому забытого
    `caffeinate` после прогона не остаётся, а настройки Мака не меняются: вне
    прогона машина спит как обычно.
    """
    try:
        proc = subprocess.Popen(['caffeinate', '-ims', '-w', str(os.getpid())])
    except OSError as err:
        logger.error(f'caffeinate не запустился ({err}): хост может уснуть '
                     f'посреди прогона, и тогда отказы будут врать про устройство')
        return None
    logger.info(f'caffeinate {proc.pid}: хост не уснёт до конца прогона')
    return proc
