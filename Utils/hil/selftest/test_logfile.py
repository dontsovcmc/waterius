"""
Лог прогона: исход теста не должен отрываться от его имени.

В файле прогона 2026-09-28 09-56 между именем теста и словом PASSED легло
1325 строк его же лога, и в файле осталась сирота «PASSED     1h 32m» - чей
это исход, по файлу узнать было нельзя. Первая починка печатала имя заново и
на разорванном дважды исходе дала строку-двойник; здесь закреплено и это.
"""
from ..conftest import _Lines


class Файл:
    """Приёмник вместо файла: копит написанное."""

    def __init__(self) -> None:
        self.text = ''

    def write(self, data: str) -> int:
        self.text += data
        return len(data)

    def flush(self) -> None:
        pass


ИМЯ = 'Utils/hil/test_alarms.py::test_E3n_single_pulse_is_not_a_leak '
ЗАПИСЬ = '11:29:24 | INFO | ping\n'


def test_исход_печатается_вместе_с_именем_теста() -> None:
    файл = Файл()
    строки = _Lines(файл)

    строки.raw(ИМЯ)                       # pytest: имя теста, без перевода
    строки.write(ЗАПИСЬ)                  # логгер посреди строки
    строки.raw('PASSED     1h 32m\n')     # pytest: исход, через час

    assert файл.text == ЗАПИСЬ + ИМЯ + 'PASSED     1h 32m\n'


def test_строка_теста_печатается_один_раз() -> None:
    """Исход приезжает кусками, и между ними снова пишет логгер."""
    файл = Файл()
    строки = _Lines(файл)

    строки.raw(ИМЯ)
    строки.write(ЗАПИСЬ)
    строки.raw('PASSED')
    строки.write(ЗАПИСЬ)
    строки.raw('     1h 32m\n')

    assert файл.text.count('test_E3n') == 1, 'строка теста не должна двоиться'
    assert файл.text.endswith(ИМЯ + 'PASSED     1h 32m\n')


def test_запись_логгера_не_приклеивается_к_строке_теста() -> None:
    файл = Файл()
    строки = _Lines(файл)

    строки.raw(ИМЯ)
    строки.write(ЗАПИСЬ)

    assert файл.text == ЗАПИСЬ, 'недописанной строке теста в файле не место'


def test_недописанная_строка_допечатывается_в_конце() -> None:
    """Прогон оборвался на середине строки - потерять её нельзя."""
    файл = Файл()
    строки = _Lines(файл)

    строки.raw(ИМЯ)
    строки.finish()

    assert файл.text == ИМЯ + '\n'


def test_целая_строка_проходит_как_есть() -> None:
    """Селф-тесты идут без записей логгера между частями строки."""
    файл = Файл()
    строки = _Lines(файл)

    строки.raw(ИМЯ + 'PASSED 0.4s\n')

    assert файл.text == ИМЯ + 'PASSED 0.4s\n'
