"""
Что делает стенд, когда приёмник пуст.

28 сентября заводской сброс оставил устройство без сети, и следующие двадцать
минут сорок семь тестов подряд падали одинаково: «приёмник не получил ни одной
посылки». Чинить было некому, останавливаться - нечем, и прогон честно
доработал до конца, не проверив ничего.

Поэтому пустой приёмник теперь сначала повод поискать устройство в эфире, а
потом - повод остановить прогон: чинить нечем, а каждый следующий тест выдаст
ту же ошибку.
"""

from __future__ import annotations

from typing import Any

import pytest

from ..stand import SILENT_LIMIT, DeviceLost, Stand


class ПустойПриёмник:
    """Сеанс, в котором до приёмника не дошло ничего."""

    payloads: list[dict[str, Any]] = []
    text = ''
    http_codes: list[int] = []
    mqtt_note = ''
    headless = False


class Молчун:
    """Стенд, у которого спрашивают только счётчик молчания."""

    def __init__(self, чинится: bool) -> None:
        self._silent = 0
        self.чинится = чинится
        self.попыток = 0

    def _rescue_device(self) -> bool:
        self.попыток += 1
        return self.чинится

    class cfg:                       # noqa: N801 - подделка, а не класс конфига
        http_url = 'http://192.168.100.18:8010/data'


def считать(стенд: Молчун, сеанс: Any) -> None:
    """Настоящий счёт стенда, вызванный без его железа."""
    Stand._note_silence(стенд, сеанс)


def test_одно_молчание_прогон_не_уносит() -> None:
    стенд = Молчун(чинится=False)
    for _ in range(SILENT_LIMIT - 1):
        считать(стенд, ПустойПриёмник())
    assert стенд._silent == SILENT_LIMIT - 1


def test_молчание_подряд_останавливает_прогон() -> None:
    стенд = Молчун(чинится=False)
    for _ in range(SILENT_LIMIT - 1):
        считать(стенд, ПустойПриёмник())
    with pytest.raises(DeviceLost, match='подряд'):
        считать(стенд, ПустойПриёмник())


def test_дошедшая_посылка_сбрасывает_счёт() -> None:
    """Иначе редкие одиночные осечки за прогон сложились бы в остановку."""
    стенд = Молчун(чинится=False)

    class Дошла(ПустойПриёмник):
        payloads = [{'key': 'abc'}]

    for _ in range(SILENT_LIMIT * 3):
        считать(стенд, ПустойПриёмник())
        считать(стенд, Дошла())
    assert стенд._silent == 0
