#ifndef _ALARM_h
#define _ALARM_h

/*
Детекция аварий по импульсам счётчика (issue #202).

Считать умеет только attiny: ЕСП спит между сеансами и импульсов не видит.
Поэтому правила живут здесь, а ЕСП получает готовое состояние, отдаёт его
наружу и задаёт пороги.

Три независимых состояния:

  ALARM_FLOW - много воды сразу: за 30 минут вылилось больше порога.
               Прорыв, срыв шланга, забытый кран.
  ALARM_LEAK - протечка: расход не падал до нуля дольше заданного времени.
               Капающий кран, текущий бачок.
  ALARM_WET  - датчик протечки на входе замкнут.

Ни одна тревога не снимается сама - ни по времени, ни по прекращению расхода.
Снимает её человек: кнопкой на корпусе или командой с сервера (reset).
Отсюда три следствия, каждое из которых убирает код:

  - гистерезиса нет: мигать на границе порога нечему;
  - бюджета внеплановых сеансов нет: переходов вниз не бывает, а значит нет и
    дребезга, против которого он был заведён;
  - held нет: держать состояние от преждевременного погасания не требуется.

Файл намеренно без Arduino.h и без обращений к регистрам: правила
проверяются хостовыми тестами (Attiny85/test/test_alarm).
*/

#include <stdint.h>

#define ALARM_FLOW 0x01
#define ALARM_LEAK 0x02
#define ALARM_WET 0x04
#define ALARM_MASK 0x07  // все тревоги канала

/*
Минут тишины после внепланового сеанса: пауза до следующей попытки доставки.
*/
#define ALARM_HOLD_MIN 5

/*
Сколько раз будим ЕСП, пока она не подтвердит доставку. Пять попыток по пять
минут - максимум 20 минут на доставку. Быстрее смысла нет: внутри сеанса ЕСП
уже делает три попытки POST и несколько попыток подключения к роутеру.
*/
#define ALARM_MAX_TRIES 5

/*
Тиков сторожевого таймера (250мс) в минуте.
*/
#define ALARM_TICKS_PER_MINUTE 240

/*
Окно большого расхода: семь слотов по пять минут.

Тридцать минут - отраслевая константа (Kamstrup, Zenner PDC, BMeters), а
нарезка на слоты даёт скользящее окно вместо обрубленного: порог набирается
в любые полчаса, а не только между круглыми получасами.

Слотов семь, а не шесть. Шесть давали бы окно от 25 до 30 минут - в момент
смены слота самый старый уже выброшен, а новый только начался. Тогда
обещание "за 30 минут" иногда нарушалось бы в опасную сторону: прорыв,
уложившийся ровно в полчаса, мог не сработать. Седьмой слот сдвигает разброс
к 30-35 минутам: теперь ошибка только в сторону чуть большей
чувствительности, а обещанные тридцать минут покрыты всегда.
*/
#define ALARM_VOL_SLOTS 7
#define ALARM_VOL_SLOT_TICKS ((uint16_t)(5 * ALARM_TICKS_PER_MINUTE))

struct AlarmDetector
{
    /*
    Настройки от ЕСП, 0 - тревога выключена.

    Пороги считает ЕСП: у неё есть вес импульса и тип счётчика, а деление на
    attiny стоит дорого. Здесь только сравнения и сложение.

    quantum_ticks - длина тишины, которую считаем остановкой воды. ЕСП получает
    её из порога в л/ч: квант = вес импульса / Q. Расход ровно в Q даёт один
    импульс за квант и потому тишины такой длины не оставляет никогда.
    */
    uint16_t quantum_ticks; // длина кванта тишины, тиков
    uint16_t leak_quanta;   // занятых квантов подряд - протечка
    uint16_t vol_pulses;    // импульсов за 30 минут - много воды сразу

    uint16_t tick_in_quantum; // тиков с начала кванта
    uint16_t busy_quanta;     // квантов подряд, в которых был импульс

    uint8_t vol[ALARM_VOL_SLOTS]; // импульсов в каждом пятиминутном слоте
    uint16_t tick_in_slot;        // тиков с начала слота
    uint8_t slot;                 // текущий слот кольца

    uint8_t state : 3;            // маска ALARM_*
    uint8_t changed : 1;          // состояние сменилось - есть о чём доложить
    uint8_t pulse_in_quantum : 1; // в текущем кванте был импульс
    uint8_t reserved : 3;

    AlarmDetector()
        : quantum_ticks(0), leak_quanta(0), vol_pulses(0),
          tick_in_quantum(0), busy_quanta(0),
          tick_in_slot(0), slot(0),
          state(0), changed(0), pulse_in_quantum(0), reserved(0)
    {
        for (uint8_t i = 0; i < ALARM_VOL_SLOTS; i++)
            vol[i] = 0;
    }

    void configure(const uint16_t quantum, const uint16_t quanta,
                   const uint16_t pulses)
    {
        quantum_ticks = quantum;
        leak_quanta = quanta;
        vol_pulses = pulses;
    }

    /*
    Импульсов в скользящем 30-минутном окне.
    */
    uint16_t window_pulses() const
    {
        uint16_t sum = 0;
        for (uint8_t i = 0; i < ALARM_VOL_SLOTS; i++)
            sum += vol[i];
        return sum;
    }

    /*
    Импульс засчитан.
    */
    void on_pulse()
    {
        pulse_in_quantum = 1;

        if (vol[slot] < 255)
        {
            vol[slot]++;
        }

        if (vol_pulses && window_pulses() >= vol_pulses)
        {
            raise(ALARM_FLOW);
        }
    }

    /*
    Прошло 250мс.
    */
    void on_tick()
    {
        // кольцо окна большого расхода
        if (++tick_in_slot >= ALARM_VOL_SLOT_TICKS)
        {
            tick_in_slot = 0;
            slot = (slot + 1 < ALARM_VOL_SLOTS) ? slot + 1 : 0;
            vol[slot] = 0;
        }

        // границы кванта тишины
        if (!quantum_ticks || ++tick_in_quantum < quantum_ticks)
        {
            return;
        }
        tick_in_quantum = 0;

        if (pulse_in_quantum)
        {
            // вода в этом кванте не остановилась
            if (busy_quanta < UINT16_MAX)
            {
                busy_quanta++;
            }
            if (leak_quanta && busy_quanta >= leak_quanta)
            {
                raise(ALARM_LEAK);
            }
        }
        else
        {
            // нашлась тишина длиной в квант: счёт начинается заново.
            // Поднятую тревогу это не снимает - снимает только человек.
            busy_quanta = 0;
        }
        pulse_in_quantum = 0;
    }

    /*
    Состояние входа с датчиком протечки.

    Только поднимает. Дребезг датчика перестаёт существовать как проблема:
    намок - высох - намок даёт одну тревогу и один сеанс.
    */
    void set_wet(const bool closed)
    {
        if (closed)
            raise(ALARM_WET);
    }

    /*
    Снять тревоги канала по маске: кнопка, команда с сервера, смена типа входа.

    Снять - значит начать счёт заново, а не погасить бит: иначе накопители
    остались бы выше порога и тревога вернулась бы на следующем же кванте.
    Так она не повторится раньше, чем через полный порог.

    Накопители обнуляются только у снятых тревог: у протечки это квант и счёт
    квантов, у большого расхода - кольцо, у датчика их нет вовсе.
    */
    void reset(const uint8_t mask)
    {
        if (state & mask)
        {
            state &= ~mask;
            changed = 1;
        }

        if (mask & ALARM_LEAK)
        {
            tick_in_quantum = 0;
            busy_quanta = 0;
            pulse_in_quantum = 0;
        }

        if (mask & ALARM_FLOW)
        {
            tick_in_slot = 0;
            slot = 0;
            for (uint8_t i = 0; i < ALARM_VOL_SLOTS; i++)
                vol[i] = 0;
        }
    }

private:
    void raise(const uint8_t bit)
    {
        if (state & bit)
            return;
        state |= bit;
        changed = 1;
    }
};

/*
Доклад о тревоге: сколько раз будили ЕСП и ждём ли подтверждения.
Один на оба канала - тревоги уезжают одним сеансом.

Потолка на число докладов здесь нет и не нужно: каждая тревога поднимается
один раз и молчит до снятия, поэтому внеплановых сеансов за всё время не
больше, чем поднятых тревог.
*/
struct AlarmReport
{
    uint8_t tries : 3;   // 0..ALARM_MAX_TRIES
    uint8_t pending : 1; // доклад не подтверждён
    uint8_t reserved : 4;

    AlarmReport() : tries(0), pending(0), reserved(0) {}

    /*
    Начинаем новый доклад: счётчик попыток с нуля.
    */
    void start()
    {
        pending = 1;
        tries = 0;
    }

    /*
    ЕСП подтвердила доставку.
    */
    void confirm()
    {
        pending = 0;
        tries = 0;
    }

    /*
    Сеанс закончился без подтверждения.

    @return true если стоит попробовать ещё раз
    */
    bool failed()
    {
        if (!pending)
            return false;

        tries++;
        if (tries >= ALARM_MAX_TRIES)
        {
            // Сдаёмся: состояние уедет со следующим плановым сеансом
            pending = 0;
            return false;
        }
        return true;
    }
};

#endif
