#ifndef _WET_h
#define _WET_h

/*
Датчик протечки на входе: решение по уровню АЦП, а не по уровню пина.

Вода между электродами - это не замыкание контактов, а сопротивление в десятки
и сотни килоом. Цифровой уровень пина такого не видит: чтобы attiny прочитала
ноль, нужно Uпин < 0.3*Vcc, то есть Rдатчика + Rпосл < 0.43*Rпод. С подтяжкой
30кОм это ~9кОм, с худшей по даташиту 20кОм - ~5кОм, а всё, что выше,
выглядит как сухо. Поэтому состояние датчика берётся с АЦП, как у namur.

Делитель: подтяжка Rпод от Vcc к пину, от пина на землю Rпосл платы (3к6 у
Classic: 3к3 в линии и 300 Ом в общем проводе; 1кОм у Ватериуса 2) и сам
датчик. Опорное напряжение АЦП - Vcc, поэтому код не зависит от заряда
батарейки:

    N = 1024 * (Rд + Rпосл) / (Rд + Rпосл + Rпод)
    Rд = N/(1024-N) * Rпод - Rпосл

Внутренняя подтяжка attiny по даташиту 20..50кОм (в комментариях counter.h -
измеренные ~30кОм), поэтому пороги выбраны так, чтобы решение не менялось на
всём этом разбросе.

Типы входа - два разных соглашения, у каждого свой порог.

LEAKAGE ("замыкание")
---------------------
В норме линия разомкнута, тревога - появилась проводимость, любая. Нижней
границы нет: замыкание 0 Ом - тоже вода. Сверху ограничивает само сухое
состояние: это та же разомкнутая линия (1013..1023, ток утечки пина <= 1мкА
на 30кОм отнимает <= 10 отсчётов), спутать с ней нельзя.

Порог 950 оставляет до сухого 53 отсчёта и ловит сопротивление до ~250кОм при
подтяжке 20кОм, ~380кОм при 30кОм и ~640кОм при 50кОм. Требуемые 100кОм дают
858 при 20кОм и 691 при 50кОм - проходят на любом чипе.

LEAKAGE_NC ("размыкание")
-------------------------
В норме шлейф замкнут - перемычкой или резистором 5к6, как у намур. Тревога -
сопротивление выше 5к6. Обрыв провода отдельно не детектируется: он просто
даёт 1023 и попадает в ту же тревогу.

5к6 даёт 323 / 240 / 159 у Classic и 254 / 185 / 119 у Ватериуса 2 при
подтяжке 20 / 30 / 50 кОм, поэтому порог 450: исправный шлейф ниже него на
любом чипе, а тревога начинается с 12..36кОм - "выше 5к6". Промахнуться в
другую сторону нельзя: размыкание даёт 1023.

Файл намеренно без Arduino.h и без обращений к регистрам: пороги проверяются
хостовыми тестами (Attiny85/test/test_wet).
*/

#include <stdint.h>

#define LIMIT_WET 950     // < 950 - датчик "замыкание" намок
#define LIMIT_WET_NC 450  // < 450 - шлейф датчика "размыкание" цел

/*
Линия проводит: уровень ниже порога. Что это значит - тревога или норма -
решает тип входа в main.cpp.
*/
inline bool adc_below(const uint16_t adc, const uint16_t limit)
{
    return adc < limit;
}

#endif
