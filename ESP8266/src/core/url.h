#ifndef _WATERIUS_CORE_URL_h
#define _WATERIUS_CORE_URL_h

/*
Разбор адресов, которые вводит пользователь.

Часть чистого ядра src/core: без Arduino.h и String.
*/

#include "types.h"
#include "input.h"

/*
Адрес MQTT брокера.

Пользователи привычно пишут адрес как URL: mqtt://broker, http://192.168.0.20,
иногда с портом и путём. PubSubClient же хочет голое имя хоста.

Схемы открытого TCP (mqtt, tcp, http) снимаются молча — это ровно то
подключение, которое прошивка и делает. Схемы с шифрованием отвергаются:
sender_mqtt.h работает через WiFiClient, а не WiFiClientSecure, поэтому
молча снять mqtts:// значило бы отправить логин и пароль открытым текстом,
оставив пользователя в уверенности, что канал защищён.

Путь отбрасывается: для MQTT поверх TCP он не значит ничего и не может
увести подключение в другое место. Порт, наоборот, увести может, поэтому
адрес с портом отвергается — иначе пользователь молча подключится не туда,
куда собирался.

Длину, пустоту и обрезку пробелов проверяет parse_text.
*/
ParamError parse_broker_host(char *dest, const size_t size, const char *value);

#endif
