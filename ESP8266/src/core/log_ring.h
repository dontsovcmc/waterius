#ifndef _WATERIUS_CORE_LOG_RING_h
#define _WATERIUS_CORE_LOG_RING_h

/*
Журнал портала: хвост лога в оперативной памяти, который пользователь
скачивает с телефона, когда Ватериус не подключается к роутеру.

Память, а не файл: журнал читают в том же сеансе портала, где он написан, а
выход из портала всё равно перезагружает ЕСП. Флеш не изнашивается, и
LittleFS, который OTA стирает целиком, не нужен.

Позиции сквозные - число байт, записанных с начала сеанса. Отдача журнала
идёт кусками, и строка, дописанная посреди отдачи, не перемешивает уже
отданное с новым: читатель видит, что его позицию затёрло, и перескакивает.

Часть чистого ядра src/core: без Arduino.h и логирования.
*/

#include <stddef.h>
#include <stdint.h>

struct LogRing
{
    char *buf = nullptr;    // nullptr - журнал не ведётся, запись ничего не делает
    size_t size = 0;
    uint32_t written = 0;   // сколько байт записано за сеанс
};

void log_ring_write(LogRing &ring, const uint8_t *data, size_t len);

/*
Первая позиция, которую ещё не затёрли.
*/
uint32_t log_ring_oldest(const LogRing &ring);

/*
Копирует в out не больше max байт с позиции pos, но не дальше end, и сдвигает
pos. Затёртое начало пропускает. Ноль - читать больше нечего.
*/
size_t log_ring_read(const LogRing &ring, uint32_t &pos, uint32_t end, uint8_t *out, size_t max);

#endif
