#ifndef _WATERIUS_CORE_WAKEUP_h
#define _WATERIUS_CORE_WAKEUP_h

/*
Подстройка периода пробуждения.

Attiny85 отсчитывает время сторожевым таймером, частота которого гуляет от
экземпляра к экземпляру и от температуры. Поэтому "проснуться через 15 минут"
на самом деле означает "проснуться через 15 кривых минут attiny". Ядро
сравнивает заказанный сон с фактическим и пересчитывает, сколько кривых минут
заказать в следующий раз, чтобы выходить на связь в одно и то же время суток.

Часть чистого ядра src/core: без Arduino.h и логирования.
*/

#include "types.h"

struct WakeupTune
{
    // Сколько минут заказать attiny на следующий сон
    uint16_t period_min_tuned = 0;
    // Сколько на самом деле проспали — нужно только для лога
    double slept_min = 0.0;
};

/*
 * @brief Корректируем период пробуждения только для автоматического режима.
 *
 * @param now - Полученное по NTP время. Должно быть валидным.
 * @param base_time - Время настройки пользователем
 * @param last_send - Предыдущее время пробуждения
 * @param wakeup_per_min - Установленный пользователем период пробуждения
 * @param period_min_tuned - Скорректированный период пробуждения
 *
 * @returns Кол-во минут ("кривых attiny"), через которое должно проснуться устройство.
 */
WakeupTune tune_wakeup(const time_t now, const time_t base_time, const time_t last_send,
                       const uint16_t wakeup_per_min, const uint16_t period_min_tuned);

/*
Период после того, как пользователь сам сменил период пробуждения:
накопленная поправка больше не годится, начинаем с заведомо меньшего значения.
*/
uint16_t period_after_user_change(const uint16_t wakeup_per_min);

#endif
