#ifndef _WATERIUS_CORE_WAKEUP_h
#define _WATERIUS_CORE_WAKEUP_h

/*
Подстройка периода пробуждения.

Attiny85 отсчитывает время сторожевым таймером, частота которого гуляет от
экземпляра к экземпляру и от температуры. Поэтому "проснуться через 15 минут"
на самом деле означает "проснуться через 15 кривых минут attiny". Ядро
сравнивает заказанный сон с фактическим и пересчитывает, сколько кривых минут
заказать в следующий раз, чтобы выходить на связь в одно и то же время суток.

Часть чистого ядра src/core: без Arduino.h и логирования.
*/

#include "types.h"

struct WakeupTune
{
    // Сколько минут заказать attiny на следующий сон, чтобы попасть
    // в ближайшую точку расписания
    uint16_t period_min_tuned = 0;
    /*
    Целый период с поправкой: сколько кривых минут attiny соответствуют
    периоду, заданному пользователем.

    Отличается от period_min_tuned тем, что не зависит от расстояния до
    ближайшей точки расписания. Нужен при ручном пробуждении: кнопка
    задаёт расписание заново, и заказывать надо целый период, а не остаток
    от прошлой цели (#380).
    */
    uint16_t period_min_full = 0;
    // Сколько на самом деле проспали — нужно только для лога
    double slept_min = 0.0;
};

/*
 * @brief Корректируем период пробуждения только для автоматического режима.
 *
 * @param now - Полученное по NTP время. Должно быть валидным.
 * @param base_time - Время настройки пользователем
 * @param measured_from - Предыдущее время, измеренное по NTP
 * @param wakeup_per_min - Установленный пользователем период пробуждения
 * @param period_min_tuned - Скорректированный период пробуждения
 * @param periods_slept - Сколько раз устройство просыпалось за это время
 *
 * periods_slept обязателен и указывается на каждом вызове: без него единственный
 * способ разделить "attiny спешит" и "не было связи три периода подряд" — гадать
 * по дробной части, и устройство после суток без интернета уезжает от расписания
 * на часы (#345, #347).
 *
 * @returns Кол-во минут ("кривых attiny"), через которое должно проснуться устройство.
 */
WakeupTune tune_wakeup(const time_t now, const time_t base_time, const time_t measured_from,
                       const uint16_t wakeup_per_min, const uint16_t period_min_tuned,
                       const uint16_t periods_slept);

/*
Период после того, как пользователь сам сменил период пробуждения:
накопленная поправка больше не годится, начинаем с заведомо меньшего значения.
*/
uint16_t period_after_user_change(const uint16_t wakeup_per_min);

/*
Период после ручного пробуждения кнопкой.

Нажатие задаёт расписание заново, поэтому заказывается целый период с
поправкой. Если поправку ещё не измеряли, остаётся заведомо меньшее
значение: проснуться раньше цели не страшно — следующий цикл доберёт,
а проснуться сильно позже значит проехать точку расписания.
*/
uint16_t period_after_manual_wakeup(const uint16_t period_min_full,
                                    const uint16_t wakeup_per_min);

#endif
