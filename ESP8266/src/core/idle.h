#ifndef _WATERIUS_CORE_IDLE_h
#define _WATERIUS_CORE_IDLE_h

/*
Режим "выходить на связь только при расходе воды" (#361).

Пользователь ставит короткий период, чтобы смотреть расход почти в реальном
времени, и платит за это батареей: устройство выходит в эфир даже ночью,
когда воду никто не трогает.

Ключевое наблюдение: проснуться и выйти на связь — разные вещи по цене.
Пробуждение остаётся прежним, каждые wakeup_per_min минут, поэтому расход
замечается ровно за период, заданный пользователем. Экономится сеанс Wi-Fi:
именно он стоит секунд работы радио, тогда как чтение attiny по i2c — доли
секунды.

Так что "период 5 минут" остаётся минимальным промежутком между выходами на
связь, как и задумано, а не превращается в "проверяем раз в 5 минут, если
повезёт".

Часть чистого ядра src/core: без Arduino.h и логирования.
*/

#include "types.h"

/*
Как долго устройство может молчать при полном отсутствии расхода.

Трое суток, а не "сколько угодно": редкий сеанс связи нужен не ради
показаний, а чтобы было видно, что устройство живо. В Zigbee и Matter этот
параметр так и называется — maximum reporting interval, и его назначение
описано как liveness check.

Число согласовано с облаком: waterius.ru считает устройство пропавшим после
max(5 суток, period_min * 2 + 2 часа). Трое суток укладываются в этот порог,
поэтому молчаливое устройство не выглядит пропавшим. А вот если отметка не
доехала и тишина дошла до пяти суток, письмо владельцу уйдёт — и правильно
сделает: устройство дважды не смогло достучаться до сервера.
*/
#define MAX_SILENCE_MIN (3UL * 24 * 60)

/*
Был ли расход за прошедший период.

Уменьшение счётчика — тоже событие: attiny обнулился (замена батареек,
сброс), и это ровно тот случай, когда выходить на связь надо, а не молчать
трое суток.
*/
bool consumption_detected(const uint32_t impulses0, const uint32_t impulses0_previous,
                          const uint32_t impulses1, const uint32_t impulses1_previous);

/*
Прибавить проспанные минуты к счётчику молчания.

Насыщается вместо переполнения: обнуление счётчика означало бы, что срок
"выйти на связь хотя бы раз в трое суток" отодвигается на новый круг.
*/
uint16_t add_minutes(const uint16_t accumulated, const uint16_t minutes);

/*
Нужно ли включать Wi-Fi в этом пробуждении.

Молчим, только если режим включён, расхода не было и срок не подошёл. Во всех
остальных случаях выходим на связь — это поведение по умолчанию, и любая
неопределённость должна разрешаться в его пользу.
*/
bool need_transmit(const bool send_on_consumption, const bool consumed,
                   const uint16_t minutes_since_send);

#endif
