#ifndef _WATERIUS_CORE_MQTT_COMMAND_h
#define _WATERIUS_CORE_MQTT_COMMAND_h

/*
Что из пришедшего по подписке является командой.

Подписка накрывает всё дерево устройства, <корень>/#, а показания уходят туда же
и с флагом retain, поэтому в следующем сеансе брокер отдаёт устройству его
собственные сообщения. Команда - только топик <корень>/<имя>/set; остальное
устройству трогать нечем, а стирать тем более: удерживаемые показания - это то,
из чего Home Assistant берёт значения сразу после перезапуска (#422).

Пустое значение командой не является. Пустое сообщение в топике команды - это
снятие retain: устройство публикует его само, приняв команду, и получает обратно
по своей же подписке. Разобрав такое сообщение, оно затрёт только что принятое
значение (#421). Пустая строка не годится в значения ни одному параметру, так
что чьё это сообщение, своё или чужое, роли не играет.

Часть чистого ядра src/core: без Arduino.h и String.
*/

#include <stddef.h>

/*
Имя параметра - позицией и длиной внутри topic: копировать его ядру некуда, а
предполагать предельную длину не из чего.
*/
bool parse_mqtt_command(const char *topic, const size_t payload_len,
                        size_t *name_pos, size_t *name_len);

#endif
