#ifndef _WATERIUS_CORE_PORTAL_WATCHDOG_h
#define _WATERIUS_CORE_PORTAL_WATCHDOG_h

/*
Сторожевой таймер режима настройки.

Таймер нужен как подстраховка: устройство может остаться включённым, если
пользователь просто ушёл. Но и обрывать настройку на полуслове неправильно,
поэтому окно продлевается на каждое действие пользователя — переход по
страницам и сохранение формы (#305).

Таймер один, и это осознанно. Автоматические опросы страниц
(`/api/status`, `/api/connect_status`) окно не продлевают, поэтому забытая
вкладка портал не держит, а питание всё равно снимет attiny: она отмеряет
свои SETUP_TIME_MSEC от того же последнего действия. Общего потолка на всю
настройку нет — он обрывал бы человека, который настраивает долго и всерьёз.

Часть чистого ядра src/core: без Arduino.h и работы с железом.
*/

#include <stdint.h>

/*
Сколько портал живёт без кормления. Столько же attiny держит питание после
команды 'E' (SETUP_TIME_MSEC в Attiny85/src/Setup.h): числа обязаны совпадать, иначе
одна сторона выключится заметно раньше другой, и продление окажется
бессмысленным.
*/
#define PORTAL_WATCHDOG_MS 600000UL

/*
Сработал ли сторожевой таймер: пора гасить портал.

Моменты времени приходят из millis(): счётчик 32-битный и переполняется
через 49 суток. Поэтому сравниваются не сами моменты, а беззнаковые
разности — они переполнение переживают, а прямое сравнение не пережило бы.
*/
bool portal_watchdog_fired(const uint32_t now_ms, const uint32_t last_feed_ms);

/*
Сколько секунд осталось порталу до закрытия.

Отдаётся наружу (`/api/portal_time`) и видно человеку, который настраивает
устройство и не понимает, почему страница вдруг перестала отвечать. Проверке
это число экономит время: продлевает ли действие окно, видно сразу, а не через
десять минут ожидания.

Истёкший срок — ноль, а не сутки: на беззнаковой разности «минус секунда»
превратилась бы в 49 суток.
*/
uint32_t portal_idle_seconds_left(const uint32_t now_ms, const uint32_t last_feed_ms);

#endif
