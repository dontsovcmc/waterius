#ifndef _WATERIUS_CORE_ALARM_h
#define _WATERIUS_CORE_ALARM_h

/*
Тревоги: пересчёт порогов для attiny и разбор её ответа (issue #202).

Детекция живёт в attiny - только она видит импульсы, пока ЕСП спит. Но у
attiny нет ни веса импульса, ни типа счётчика, а деление на ней дорого,
поэтому пороги в понятных человеку единицах пересчитывает ЕСП, а attiny
получает готовое число тиков и только сравнивает.

Часть чистого ядра src/core: без Arduino.h.

Что означает каждая тревога и когда снимается - docs/alarms.md.
*/

#include "types.h"
#include "blink.h"

/*
Тиков сторожевого таймера attiny (250мс) в часе.
*/
#define ALARM_TICKS_PER_HOUR 14400UL

/*
Пороги тревог для attiny: три числа на канал.

Человек задаёт литры, литры в час и часы. attiny считает тиками и квантами -
делить там дорого, а веса импульса она не знает. Поэтому весь пересчёт здесь.

Квант тишины - это длина паузы, которую считаем остановкой воды. Он не
отдельная настройка, а тот же порог расхода в других единицах: расход ровно в
Q даёт один импульс за квант и потому паузы такой длины не оставляет никогда.

    квант  = вес импульса / Q          (в тиках: 14400 * вес / Q)
    Q      = вес импульса / квант
*/
struct AlarmThresholds
{
    uint16_t quantum_ticks; // длина кванта тишины, тиков по 250мс
    uint16_t leak_quanta;   // занятых квантов подряд - протечка
    uint16_t vol_pulses;    // импульсов за 30 минут - много воды сразу
};

/*
Литры за 30 минут -> импульсов в окне. @return 0 если выключено
*/
uint16_t volume_to_pulses(const uint16_t litres, const uint16_t factor);

/*
Порог "остановки воды" в л/ч -> длина кванта тишины в тиках.
@return 0 если выключено
*/
uint16_t rate_to_quantum_ticks(const uint16_t rate, const uint16_t factor);

/*
Часы -> сколько квантов подряд должны быть заняты. @return 0 если выключено
*/
uint16_t hours_to_quanta(const uint16_t hours, const uint16_t rate,
                         const uint16_t factor);

/*
Минимальный порог расхода, который ещё можно посчитать: длина кванта обязана
влезть в uint16. При весе 10 л/имп это 3 л/ч. Для проверки ввода в портале.
*/
uint16_t alarm_min_rate(const uint16_t factor);

/*
Минимальные часы протечки: два кванта. Один квант - это не "расход не
прекращался", а всего лишь "был хоть один импульс". Для проверки ввода.
*/
uint16_t alarm_min_hours(const uint16_t rate, const uint16_t factor);

/*
Пороги канала целиком, включая режим "я уехал" (#88).

Уехал - тревогой становится любой расход: порог объёма подменяется одним
импульсом. Вес импульса для этого не нужен, поэтому режим работает и на
канале, где вес ещё не задан. Протечка в этом режиме не считается - объём
сработает раньше на первом же импульсе.

Обычные пороги без веса посчитать нельзя: до первой настройки входа там лежит
спецзначение (AUTO_IMPULSE_FACTOR или AS_COLD_CHANNEL), и взять его за литры
на импульс значило бы отдать attiny порог, о котором никто не просил.

@param counter_type тип входа: у датчика протечки и выключенного входа
       импульсов нет, порогам неоткуда взяться
*/
AlarmThresholds alarm_thresholds(const bool vacation, const uint8_t counter_type,
                                 const uint16_t vol, const uint16_t rate,
                                 const uint16_t hours, const uint16_t factor);

/*
Что страница тревог может показать на входе.

Порядок = приоритет: вход без импульсов не спасёт ни новая attiny, ни
заданный вес, а на старой attiny звать настраивать счётчик бессмысленно -
порогов там всё равно не будет.

Состояния взаимоисключающие, поэтому странице хватает одного признака:
она вешает его классом на блок канала, а показ решает CSS.
*/
enum AlarmInputState : uint8_t
{
    ALARM_INPUT_READY = 0,   // всё доступно
    ALARM_INPUT_NO_FACTOR,   // вес импульса не задан: порог не пересчитать в тики
    ALARM_INPUT_NO_ATTINY,   // attiny старее ATTINY_VER_ALARM: пороги считает она
    ALARM_INPUT_NO_INPUT     // вход не считает импульсы: тревог нет вовсе
};

AlarmInputState alarm_input_state(const uint8_t counter_type, const uint16_t factor,
                                  const uint8_t attiny_version);

/*
Тревоги одного входа из байта флагов attiny.

@param input INPUT0_RED или INPUT1_BLUE
@return маска ALARM_*, ноль для attiny старее ATTINY_VER_ALARM: там в этом
        байте лежит только флаг питания
*/
uint8_t alarm_bits(const uint8_t attiny_flags, const uint8_t input,
                   const uint8_t attiny_version);

/*
Байт флагов после снятия тревог маской (#202).

Снимок attiny обновляется раз в сеанс, а плашка в портале обязана погаснуть
сразу после нажатия. Раскладки разные: в маске кадра 'A' каналы лежат
вплотную (биты 0-2 и 3-5), в флагах - со сдвигом под флаг питания.

@param reset_mask маска в раскладке кадра 'A'
*/
uint8_t alarm_flags_after_reset(const uint8_t attiny_flags, const uint8_t reset_mask);

/*
Докладывать ли attiny, что тревога доставлена (#202).

Пока квитанции нет, attiny будит ЕСП снова - до ALARM_MAX_TRIES попыток.
Поэтому "доставлено" стоит батареи, и решать, кому доклад обязан доехать,
должен пользователь: маска mask отмечает обязательных получателей.

Обязательным считается только настроенный получатель. Выключенный
приезжает как SEND_SKIPPED, и требование к нему снимается - иначе галочка
на брокере, который потом выключили (а сделать это можно и удалённо, из
Home Assistant), стоила бы всех пяти попыток на каждой тревоге. Если обязательных не осталось совсем, работает правило
"достаточно любого".

@param mask маска CONFIRM_*; ноль - достаточно любого получателя
*/
bool alarm_delivered(const uint8_t mask, const SessionStatus &status);

#endif
