#ifndef _WATERIUS_CORE_WIFI_h
#define _WATERIUS_CORE_WIFI_h

/*
Канал и BSSID точки доступа: разбор того, что прислал портал, и правила их
применения.

Зачем это вообще нужно. ЕСП умеет подключаться к роутеру «вслепую» — с
указанием канала и BSSID, без полного скана эфира. Скан занимает секунды
работы радио, а это главная статья расхода батареи в сеансе. Канал и BSSID
известны уже в момент, когда пользователь выбирает сеть в портале: их отдаёт
тот же скан, который рисует список.

Часть чистого ядра src/core: без Arduino.h.
*/

#include "types.h"

/*
Диапазон каналов 2,4 ГГц, который принимает SDK.
*/
#define WIFI_CHANNEL_MIN 1
#define WIFI_CHANNEL_MAX 13

/*
Номер канала из скрытого поля формы. Ноль означает «канал неизвестен, идём
полным сканом» — это не ошибка пользователя: поле заполняет не он, а список
сетей, и пустым оно бывает при ручном вводе имени сети.
*/
uint8_t parse_wifi_channel(const char *value);

/*
MAC точки доступа из скрытого поля формы: aa:bb:cc:dd:ee:ff, aa-bb-... или
двенадцать hex-символов подряд. При неудаче обнуляет out — половина
разобранного адреса хуже, чем его отсутствие.
*/
bool parse_bssid(const char *value, uint8_t out[6]);

/*
Задан ли BSSID. Проверять приходится, потому что WiFi.begin считает адрес
заданным по самому факту ненулевого указателя, а в настройках лежит массив:
указатель ненулевой всегда, и нулевой адрес превратился бы в попытку
подключиться к точке 00:00:00:00:00:00.
*/
bool has_bssid(const uint8_t bssid[6]);

/*
Канал для точки доступа портала. В настройках канал штатно бывает нулём —
его обнуляют неудачный коннект и смена сети, — а SDK принимает только
1..13 и на нуле точку доступа может не поднять.
*/
uint8_t ap_channel(const uint8_t channel);

#endif
