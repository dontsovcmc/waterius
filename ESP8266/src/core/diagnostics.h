#ifndef _WATERIUS_CORE_DIAGNOSTICS_h
#define _WATERIUS_CORE_DIAGNOSTICS_h

/*
Проверки настройки счётчиков (#283).

Ошибка настройки не мешает устройству работать: оно исправно считает и
отправляет неправильные показания. Заметить её можно только по расходу,
накопленному за недели, поэтому проверки живут в портале - там, где их есть
кому исправить, и там же, где пользователь оказывается, когда что-то
заподозрил.

Часть чистого ядра src/core: без Arduino.h и логирования. Адаптер -
get_api_main_status() в portal/active_point_api.cpp, он раскладывает
результат по плашкам главной страницы.

Обе проверки молчат, пока не уверены: ложная плашка у исправного
устройства заставит человека перенастроить то, что работало.
*/

#include "types.h"

/*
Сколько должно вылиться на каждом канале, чтобы их вообще сравнивать.
*/
#define COMPARE_MIN_LITERS 200

/*
Во сколько раз должен разойтись расход, чтобы подозревать вес импульса.

Ошибка автоопределения кратна десяти, порог взят с запасом вниз: холодной
воды в квартире уходит втрое-вчетверо больше горячей, и это норма.
*/
#define SUSPICIOUS_RATIO 5

/*
Сколько импульсов должен насчитать соседний вход, чтобы молчание первого
что-то значило: у только что настроенного устройства молчат оба.

Считаем в импульсах, а не в литрах: соседом бывает газ или электричество.
Двадцать импульсов - это те же 200 литров на водяном счётчике 10 л/имп.
*/
#define NEIGHBOUR_MIN_IMPULSES 20

/*
Что не так с настройкой входов. Пустая структура - вопросов нет.
*/
struct SetupProblems
{
    /*
    Вес импульса похож на завышенный в 10 раз: канал насчитал кратно
    больше соседа, у которого вес ровно вдесятеро легче.
    */
    bool factor_too_big0 = false;
    bool factor_too_big1 = false;

    /*
    Вход настроен, сосед считает, а этот не насчитал ни одного импульса.
    */
    bool silent_input0 = false;
    bool silent_input1 = false;
};

/*
Проверяет настройку по расходу, накопленному с момента ввода показаний.

data - снимок импульсов на момент загрузки, sett - настройки. Стартовые
импульсы в sett уезжают на текущие, когда пользователь заново вводит
показания, поэтому исправленная настройка гасит плашку сама.
*/
SetupProblems check_setup(const Settings &sett, const AttinyData &data);

#endif
