#ifndef _WATERIUS_CORE_TIMEKEEPING_h
#define _WATERIUS_CORE_TIMEKEEPING_h

/*
Работа со временем: что считать валидным временем, разбор ответа NTP-сервера,
обход пула серверов.

Часть чистого ядра src/core: без Arduino.h и без сети. В sync_time.cpp
остаётся только сетевая обвязка — UDP и settimeofday.
*/

#include "types.h"

/*
Раньше этой даты время считается недостоверным: устройство либо ни разу не
синхронизировалось, либо часы сбились.
*/
#define START_VALID_TIME 1704067201UL // Jan 01 2024 00:00:01

/* Секунд от 1900 (эпоха NTP) до 1970 (эпоха unix) */
#define SEVENTY_YEARS 2208988800UL

#define NSEC 1000000000UL

/* Ответ NTP: время лежит в первых 48 байтах */
#define NTP_PACKET_SIZE 48

/* Серверы пула 0.ru.pool.ntp.org ... 3.ru.pool.ntp.org */
#define NTP_POOL_SIZE 4

bool is_valid_time(const time_t time);

/*
Какое время поставить на часы перед запросом к NTP.

Часы приходится выставлять до запроса, и если запрос не удался, устройство
остаётся с этим значением. Ставить заведомо старую дату нельзя: тогда
получается now < last_send, то есть "проснулись раньше, чем засыпали", и
подстройка периода считается по отрицательному сну.

Поэтому берём последнее достоверно известное время. У нового устройства
его нет — тогда остаётся START_VALID_TIME, и проверка is_valid_time не даст
испортить конфигурацию.
*/
time_t clock_before_sync(const time_t last_send);

/*
Разбор ответа NTP-сервера: 48 байт на входе, наносекунды от эпохи unix
на выходе. Ноль означает "ответ негоден".

Компенсация задержки сюда не входит — она про время ожидания, а не про
содержимое пакета.
*/
uint64_t parse_ntp_packet(const uint8_t *packet, const size_t size);

/*
Следующий сервер пула по кругу. Первый сервер выбирается случайно,
и этот выбор остаётся снаружи: random() не чистая функция.
*/
int next_ntp_server_id(const int current);

#endif
