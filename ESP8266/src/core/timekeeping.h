#ifndef _WATERIUS_CORE_TIMEKEEPING_h
#define _WATERIUS_CORE_TIMEKEEPING_h

/*
Работа со временем: что считать валидным временем, разбор ответа NTP-сервера,
обход пула серверов.

Часть чистого ядра src/core: без Arduino.h и без сети. В sync_time.cpp
остаётся только сетевая обвязка — UDP и settimeofday.
*/

#include "types.h"

/*
Раньше этой даты время считается недостоверным: устройство либо ни разу не
синхронизировалось, либо часы сбились.
*/
#define START_VALID_TIME 1704067201UL // Jan 01 2024 00:00:01

/* Секунд от 1900 (эпоха NTP) до 1970 (эпоха unix) */
#define SEVENTY_YEARS 2208988800UL

#define NSEC 1000000000UL

/* Ответ NTP: время лежит в первых 48 байтах */
#define NTP_PACKET_SIZE 48

/* Серверы пула 0.ru.pool.ntp.org ... 3.ru.pool.ntp.org */
#define NTP_POOL_SIZE 4

/*
Как часто синхронизировать время. Раньше NTP опрашивался при каждом
пробуждении: на суточном периоде это 365 запросов в год, на 15-минутном —
35 тысяч. Часы нужны только для расписания выхода на связь, TLS работает
с setInsecure и во времени не нуждается, поэтому недели достаточно.
*/
#define NTP_SYNC_INTERVAL_SEC (7UL * 24 * 60 * 60)

/*
Отступ после неудачи растёт как 2^N пробуждений, но не бесконечно:
у устройства, оставшегося без интернета надолго, пауза не должна
превысить срок службы батареи. 2^6 = 64 пробуждения.
*/
#define NTP_BACKOFF_MAX_SHIFT 6

/*
Поправка частоты attiny считается по паре синхронизаций: одна даёт начало
отсчёта, вторая — конец. Пока пары нет, устройство идёт с периодом из
настройки и уезжает от расписания. Поэтому первые синхронизации делаем
подряд, а на недельный график переходим уже с измеренной поправкой.
*/
#define NTP_WARMUP_SYNCS 2

bool is_valid_time(const time_t time);

/*
Какое время поставить на часы перед запросом к NTP.

Часы приходится выставлять до запроса, и если запрос не удался, устройство
остаётся с этим значением. Ставить заведомо старую дату нельзя: тогда
получается now < last_send, то есть "проснулись раньше, чем засыпали", и
подстройка периода считается по отрицательному сну.

Поэтому берём последнее достоверно известное время. У нового устройства
его нет — тогда остаётся START_VALID_TIME, и проверка is_valid_time не даст
испортить конфигурацию.
*/
time_t clock_before_sync(const time_t last_send);

/*
Разбор ответа NTP-сервера: 48 байт на входе, наносекунды от эпохи unix
на выходе. Ноль означает "ответ негоден".

Компенсация задержки сюда не входит — она про время ожидания, а не про
содержимое пакета.
*/
uint64_t parse_ntp_packet(const uint8_t *packet, const size_t size);

/*
Увеличить счётчик пробуждений с последней синхронизации.

Насыщается вместо переполнения: счётчик — делитель при расчёте поправки
частоты attiny, и обнуление на 65536-м пробуждении завысило бы поправку
в разы. Устройство с минутным периодом добирается до потолка за 45 суток
непрерывного отсутствия связи.
*/
uint16_t bump_wakeups(const uint16_t wakeups);

/*
Пора ли синхронизировать время.

Синхронизируемся раз в NTP_SYNC_INTERVAL_SEC, считая не секунды, а
пробуждения: между пробуждениями часов нет, а число проспанных периодов
известно точно.

После неудачи следующая попытка откладывается на 2^N пробуждений, где N —
номер попытки подряд. Иначе устройство с лежащим роутером опрашивает NTP
при каждом пробуждении и тратит батарею на заведомо безнадёжный запрос.

@param last_sync время последней успешной синхронизации
@param wakeups_since_sync пробуждений с тех пор, включая текущее
@param fail_count неудачных попыток подряд (сбрасывается при успехе)
@param wakeup_per_min период пробуждения, заданный пользователем
@param sync_count сколько успешных синхронизаций уже было (для прогрева)
*/
bool need_ntp_sync(const time_t last_sync, const uint16_t wakeups_since_sync,
                   const uint8_t fail_count, const uint16_t wakeup_per_min,
                   const uint8_t sync_count);

/*
Оценка текущего времени между синхронизациями: к последней синхронизации
добавляем проспанные периоды. Поправка частоты attiny уже учтена в
period_min_tuned, поэтому каждый сон считаем равным заказанному периоду.

Ноль означает "оценивать не от чего" — у вызывающего кода остаётся
clock_before_sync.
*/
time_t estimate_time(const time_t last_sync, const uint16_t wakeups_since_sync,
                     const uint16_t wakeup_per_min);

/*
Следующий сервер пула по кругу. Первый сервер выбирается случайно,
и этот выбор остаётся снаружи: random() не чистая функция.
*/
int next_ntp_server_id(const int current);

#endif
