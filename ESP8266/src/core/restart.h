#ifndef _WATERIUS_CORE_RESTART_h
#define _WATERIUS_CORE_RESTART_h

/*
Признак того, что ЕСП перезагрузилась внутри одного включения (#354).

Питание ЕСП снимает attiny, поэтому обычная загрузка начинается с чистого
листа. Если ЕСП стартовала повторно, пока питание не снимали, пользователь
в портале видит, как настройка вдруг началась заново, и не понимает почему.

Признаков два, и они дополняют друг друга:

  - причина ресета у самой ЕСП. Живёт в RTC-памяти, переживает софт-ресет и
    теряется при снятии питания, то есть говорит ровно про текущее
    включение. Различает падения самой ЕСП, но не отличит просадку питания
    от обычного включения;
  - флаг attiny "питание подано давно". Не зависит от причины, поэтому
    ловит и просадку, и внешний сброс. Приезжает только с версии
    ATTINY_VER_POWER_FLAGS: прошивка attiny обновляется программатором, а
    не по воздуху, так что у устройств в поле останется только первый.
*/

#include <stdint.h>

/*
Причины перезагрузки ЕСП, значения rst_reason из user_interface.h. Ядро
собирается без SDK, поэтому список продублирован здесь; менять значения
нельзя - это ABI SDK.
*/
#define RST_DEFAULT 0        // включение питания
#define RST_WDT 1            // аппаратный сторожевой таймер
#define RST_EXCEPTION 2      // исключение
#define RST_SOFT_WDT 3       // программный сторожевой таймер
#define RST_SOFT_RESTART 4   // ESP.restart()
#define RST_DEEP_SLEEP 5     // выход из deep sleep
#define RST_EXT_SYS 6        // внешний сброс

/*
Перезагрузилась ли ЕСП при живом питании.

Считается один раз при загрузке: флаг attiny взводится через несколько
секунд после подачи питания и дальше остаётся взведённым весь сеанс, так
что позже он уже ни о чём не говорит.

@param reset_reason причина ресета ЕСП (rst_info::reason)
@param attiny_version версия прошивки attiny
@param attiny_flags байт флагов из AttinyData
@returns true, если хотя бы один признак сработал
*/
bool esp_restarted(const uint8_t reset_reason,
                   const uint8_t attiny_version,
                   const uint8_t attiny_flags);

#endif
