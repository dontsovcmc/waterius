#ifndef _WATERIUS_CORE_PORTAL_h
#define _WATERIUS_CORE_PORTAL_h

/*
Сколько живёт режим настройки.

Таймер нужен как подстраховка: устройство может остаться включённым, если
пользователь просто ушёл. Но и обрывать настройку на полуслове неправильно,
поэтому окно продлевается на каждое действие пользователя — переход по
страницам и сохранение формы (#305).

Часть чистого ядра src/core: без Arduino.h и работы с железом.
*/

#include <stdint.h>

/*
Окно бездействия. Столько же attiny держит питание после команды 'E'
(SETUP_TIME_MSEC в Attiny85/src/Setup.h): числа обязаны совпадать, иначе
одна сторона выключится заметно раньше другой, и продление окажется
бессмысленным.
*/
#define PORTAL_IDLE_MS 600000UL

/*
Предел всей настройки. Активность продлевает окно, но не бесконечно:
страница определения счётчика опрашивает устройство сама, и забытая
открытая вкладка иначе держала бы Wi-Fi, пока не сядут батарейки.
*/
#define PORTAL_MAX_MS 1800000UL

/*
Пора ли гасить портал.

Моменты времени приходят из millis(): счётчик 32-битный и переполняется
через 49 суток. Поэтому сравниваются не сами моменты, а беззнаковые
разности — они переполнение переживают, а прямое сравнение не пережило бы.
*/
bool portal_expired(const uint32_t now_ms, const uint32_t started_ms, const uint32_t last_activity_ms);

/*
Кончилось именно общее время, а не окно бездействия. Нужно только для
внятной строки в логе: причины две, и они означают разное.
*/
bool portal_time_limit_reached(const uint32_t now_ms, const uint32_t started_ms);

#endif
