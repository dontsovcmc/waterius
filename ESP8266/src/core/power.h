#ifndef _WATERIUS_CORE_POWER_h
#define _WATERIUS_CORE_POWER_h

#include <stdint.h>

/*
Заряд батареек по одному наблюдению: под передачей напряжение проседает, и чем
сильнее, тем меньше осталось. Растущее внутреннее сопротивление видно задолго
до того, как напряжение покоя доберётся до порога, поэтому просадка и служит
главным признаком, а абсолютный порог - страховкой.

Устройству, питающемуся не от батареек, эта мерка не подходит вовсе: просадка
у него говорит про кабель и источник. Отличаем по напряжению - тем же способом
и порогом, каким это делает обновление по воздуху.

Часть чистого ядра src/core: без Arduino.h и логирования.
*/

/*
Выше этого напряжения питание внешнее.

Свежий комплект из трёх щелочных элементов даёт около 4,8 В под нагрузкой и
садится дальше, а USB держит 5 В, поэтому граница разводит эти два случая с
запасом в обе стороны.
*/
#define USB_VOLTAGE_MV 4600

/*
Расхождение замеров за сеанс, после которого батарейки считаются севшими.
*/
#define ALERT_POWER_DIFF_MV 100

/*
Начало разряда: до этой просадки уровень считается по одной шкале, после - по
другой, вдвое более крутой. Обе сходятся ровно на этой границе, поэтому менять
порог в отрыве от `ALERT_POWER_DIFF_MV` нельзя - шкала разорвётся.
*/
#define LOW_BATTERY_DIFF_MV 50

/*
Абсолютный порог: ниже него батарейки сели, как бы ни вела себя просадка.
*/
#define BATTERY_LOW_THRESHOLD_MV 2900

/*
Питается ли устройство не от батареек.
*/
bool usb_powered(const uint16_t avg_mv);

/*
Требуют ли батарейки замены.

@param avg_mv среднее напряжение за сеанс
@param diff_mv расхождение между наибольшим и наименьшим замерами
*/
bool low_voltage(const uint16_t avg_mv, const uint16_t diff_mv);

/*
Уровень батареи в процентах. У внешнего питания уровня нет - отвечаем полным,
иначе просадка кабеля поднимет тревогу о замене несуществующих батареек.
*/
uint8_t battery_level(const uint16_t avg_mv, const uint16_t diff_mv);

#endif
